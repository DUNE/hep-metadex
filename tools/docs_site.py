"""Maintainer toolchain entry point for the hep-metadex documentation site.

Stages ``docs/`` into a scratch ``.site-src/`` tree, rewriting every
out-of-tree relative link (any inline link whose target begins with
``../``) to an absolute GitHub blob URL derived from the ``repo_url``
setting of the committed ``zensical.toml``, then drives Zensical against
a derived config so the strict build sees only in-tree pages and
external links.

Usage (from the repository root):

    uv run tools/docs_site.py build   # stage + `zensical build --strict`
    uv run tools/docs_site.py serve   # stage + `zensical serve`
"""

import argparse
import copy
import math
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

COMMITTED_CONFIG_NAME = "zensical.toml"
STAGING_DIR_NAME = ".site-src"
DERIVED_CONFIG_NAME = ".site-src.toml"
DERIVED_DOCS_DIR = ".site-src"
REPO_ROOT = Path(__file__).resolve().parent.parent

# An inline Markdown link whose target escapes the docs tree, with an
# optional trailing #fragment.
_OUT_OF_TREE_LINK = re.compile(r"\]\((\.\./[^)\s]+?)(#[^)\s]*)?\)")
_LEADING_PARENT_DIRS = re.compile(r"^(?:\.\./)+")
# A fenced code block delimiter: ``` (optionally indented up to three
# spaces, optionally with an info string after the backticks).
_FENCE_LINE = re.compile(r"^\s{0,3}```")


class DocsSiteError(Exception):
    """A user-facing failure: bad or missing config, missing inputs."""


def rewrite_out_of_tree_links(text: str, repo_url: str) -> tuple[str, int]:
    """Rewrite every ``../``-escaping inline link to a GitHub blob URL.

    Each rewritten link becomes ``{repo_url}/blob/main/{path}`` with all
    leading ``../`` segments stripped and any ``#anchor`` fragment kept.
    Links inside fenced code blocks are example text, not navigation, and
    are left untouched. Returns the rewritten text and the number of
    links rewritten.
    """
    blob_base = repo_url.rstrip("/") + "/blob/main"
    lines: list[str] = []
    rewritten = 0
    in_fence = False
    for line in text.splitlines(keepends=True):
        if _FENCE_LINE.match(line):
            in_fence = not in_fence
            lines.append(line)
            continue
        if in_fence:
            lines.append(line)
            continue
        new_line, count = _rewrite_line(line, blob_base)
        rewritten += count
        lines.append(new_line)
    return "".join(lines), rewritten


def _rewrite_line(line: str, blob_base: str) -> tuple[str, int]:
    count = 0

    def replace(match: re.Match[str]) -> str:
        nonlocal count
        count += 1
        target = _LEADING_PARENT_DIRS.sub("", match.group(1))
        return f"]({blob_base}/{target}{match.group(2) or ''})"

    return _OUT_OF_TREE_LINK.sub(replace, line), count


def load_config(config_path: Path) -> dict:
    """Load the committed Zensical config, requiring ``[project] repo_url``.

    The ``repo_url`` setting is the single source for the out-of-tree link
    rewrite base, so a config without it cannot drive a site build.
    """
    if not config_path.is_file():
        raise DocsSiteError(
            f"{config_path} not found — the docs site build requires the "
            f"committed {COMMITTED_CONFIG_NAME}"
        )
    with open(config_path, "rb") as handle:
        config = tomllib.load(handle)
    if "repo_url" not in config.get("project", {}):
        raise DocsSiteError(
            f"{config_path} is missing the required [project] repo_url setting — "
            "out-of-tree link rewriting derives GitHub URLs from it"
        )
    return config


def derive_config_text(config: dict) -> str:
    """Return a derived config whose ``docs_dir`` points at the staging tree.

    Every other setting passes through unchanged. The derived file lives at
    the repository root because ``docs_dir`` resolves relative to the config
    file and Zensical rejects ``docs_dir = "."``.
    """
    derived = copy.deepcopy(config)
    derived.setdefault("project", {})["docs_dir"] = DERIVED_DOCS_DIR
    return _emit_toml(derived)


_BARE_KEY = re.compile(r"[A-Za-z0-9_-]+")


def _emit_toml(data: dict) -> str:
    lines = ["# Generated by tools/docs_site.py — do not edit."]
    _emit_table(lines, data, ())
    return "\n".join(lines) + "\n"


def _emit_table(lines: list[str], table: dict, prefix: tuple[str, ...]) -> None:
    if prefix:
        if lines:
            lines.append("")
        lines.append("[" + ".".join(_toml_key(part) for part in prefix) + "]")
    for key, value in table.items():
        if not isinstance(value, dict):
            lines.append(f"{_toml_key(key)} = {_toml_value(value)}")
    for key, value in table.items():
        if isinstance(value, dict):
            _emit_table(lines, value, prefix + (key,))


def _toml_key(key: str) -> str:
    if _BARE_KEY.fullmatch(key):
        return key
    return _toml_string(key)


def _toml_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return _toml_string(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return _toml_float(value)
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        return (
            "{ "
            + ", ".join(
                f"{_toml_key(key)} = {_toml_value(item)}" for key, item in value.items()
            )
            + " }"
        )
    raise DocsSiteError(f"cannot emit {type(value).__name__} as TOML")


def _toml_float(value: float) -> str:
    if math.isnan(value):
        return "nan"
    if math.isinf(value):
        return "inf" if value > 0 else "-inf"
    return repr(value)


def _toml_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def stage_docs(docs_dir: Path, staging_dir: Path, repo_url: str) -> tuple[int, int]:
    """Stage the docs tree into ``staging_dir``, rewriting out-of-tree links.

    The staging directory is wiped and recreated on every run so staging is
    clean. Every file in the tree is copied; Markdown pages additionally get
    their out-of-tree links rewritten on the way through. Returns the number
    of pages staged and the number of links rewritten.
    """
    if not docs_dir.is_dir():
        raise DocsSiteError(f"docs directory not found: {docs_dir}")
    shutil.rmtree(staging_dir, ignore_errors=True)
    staging_dir.mkdir(parents=True)
    pages = 0
    rewritten = 0
    for source in sorted(path for path in docs_dir.rglob("*") if path.is_file()):
        target = staging_dir / source.relative_to(docs_dir)
        target.parent.mkdir(parents=True, exist_ok=True)
        if source.suffix == ".md":
            text = source.read_text(encoding="utf-8")
            staged, count = rewrite_out_of_tree_links(text, repo_url)
            target.write_text(staged, encoding="utf-8")
            pages += 1
            rewritten += count
        else:
            shutil.copy2(source, target)
    return pages, rewritten


def _resolve_zensical(repo_root: Path) -> str:
    """Locate the zensical executable (PATH first, then the project venv)."""
    executable = shutil.which("zensical")
    if executable:
        return executable
    venv_candidate = repo_root / ".venv" / "bin" / "zensical"
    if venv_candidate.is_file():
        return str(venv_candidate)
    raise DocsSiteError(
        "zensical not found — run via `uv run tools/docs_site.py ...` so the "
        "project environment (with the zensical dev dependency) is active"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="tools/docs_site.py",
        description=(
            "Build or preview the documentation site from a staged copy of docs/ "
            "with out-of-tree links rewritten to GitHub URLs."
        ),
    )
    subcommands = parser.add_subparsers(dest="command", required=True)
    subcommands.add_parser(
        "build",
        help="stage docs/, rewrite out-of-tree links, run a strict zensical build",
    )
    subcommands.add_parser(
        "serve",
        help="stage docs/, rewrite out-of-tree links, preview via zensical serve",
    )
    args = parser.parse_args(argv)

    try:
        config = load_config(REPO_ROOT / COMMITTED_CONFIG_NAME)
        project = config["project"]
        repo_url = project["repo_url"]
        docs_dir = REPO_ROOT / project.get("docs_dir", "docs")
        pages, rewritten = stage_docs(
            docs_dir, REPO_ROOT / STAGING_DIR_NAME, repo_url
        )
        (REPO_ROOT / DERIVED_CONFIG_NAME).write_text(
            derive_config_text(config), encoding="utf-8"
        )
        zensical = _resolve_zensical(REPO_ROOT)
    except DocsSiteError as error:
        print(f"docs_site: {error}", file=sys.stderr)
        return 1

    print(
        f"Staged {pages} page{'s' if pages != 1 else ''} into {STAGING_DIR_NAME}/ "
        f"with {rewritten} out-of-tree link{'s' if rewritten != 1 else ''} rewritten."
    )

    command = [zensical, args.command]
    if args.command == "build":
        command.append("--strict")
    command += ["--config-file", DERIVED_CONFIG_NAME]
    return subprocess.call(command, cwd=REPO_ROOT)


if __name__ == "__main__":
    sys.exit(main())
